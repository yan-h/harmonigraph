// Regenerate Rust policy parity fixtures after an intentional model change.
// Run from the repository root; the fixture records every assigned onset.
import { writeFileSync } from 'node:fs';
import { EXAMPLES } from './examples.mjs';
import { DEFAULTS, Simulator, parseProgram } from './model.mjs';
// Every setting an example can declare, named on the case line in the plugin's
// own integer units. A case line carrying only some of them replays the rest at
// the plugin's defaults, so an example overriding one would agree for the wrong
// reason. A setting added to DEFAULTS with no unit here throws rather than
// going missing, and the Rust side refuses a name it does not know.
const UNITS = {
  radius: ['radius', 1], axes: ['axes', 1], pitchFlexibility: ['flexibility', 1],
  halfLife: ['half-life-ms', 1000], register: ['register', 1000], tolerance: ['tolerance', 1e6],
  silence: ['silence-ms', 1000], resetStop: ['reset-stop', 1], resetLoop: ['reset-loop', 1],
};
const profile = settings => Object.keys(DEFAULTS).map(name => {
  if (!UNITS[name]) throw new Error(`Setting “${name}” has no plugin unit; give it one so the fixture carries it.`);
  const [key, scale] = UNITS[name];
  return `${key}=${Math.round(Number(settings[name]) * scale)}`;
}).join(' ');
const lines = ['# Generated by tools/adaptive-tuning-simulator/export-plugin-fixtures.mjs'];
for (const example of EXAMPLES) {
  const sim = new Simulator(example.settings);
  lines.push(`case ${example.id} ${profile(sim.settings)}`);
  for (const entry of example.seed || []) {
    sim.seed([entry]);
    const voice = sim.held.get(entry.id);
    lines.push(`seed ${entry.id} ${Math.round(voice.output * 1e6)} ${entry.node.join(' ')}`);
  }
  for (const event of parseProgram(example.program)) {
    const result = sim.event(event);
    if (event.type === 'on') lines.push(`on ${event.id} ${Math.round(event.pitch * 1e6)} ${result.winner.node?.join(' ') ?? 'none'} ${Math.round(result.winner.output * 1e6)}`);
    else if (event.type === 'off') lines.push(`off ${event.id}`);
    else if (event.type === 'wait') lines.push(`wait ${event.seconds}`);
    else if (event.type === 'bend') lines.push(`bend ${event.id} ${event.cents}`);
    else lines.push(event.type);
  }
}
writeFileSync('crates/harmonigraph-core/src/policy/fixtures.txt', lines.join('\n') + '\n');
